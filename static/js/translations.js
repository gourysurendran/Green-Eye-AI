function changeLanguage(lang) {
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            // Check if it's an input placeholder or text content
            if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
                element.placeholder = translations[lang][key];
            } else if (element.tagName === 'A' && key.includes('_url')) {
                element.href = translations[lang][key];
            } else {
                // If the element has children (like spans or icons), only update the text nodes
                if (element.children.length > 0) {
                    // Custom logic for elements with icons/inner spans
                    // We check if there's a specific pattern like <i></i> Text
                    const icon = element.querySelector('i');
                    if (icon) {
                        element.innerHTML = '';
                        element.appendChild(icon);
                        element.appendChild(document.createTextNode(' ' + translations[lang][key]));
                    } else {
                        element.innerHTML = translations[lang][key];
                    }
                } else {
                    element.innerHTML = translations[lang][key];
                }
            }
        }
    });
    localStorage.setItem('preferredLanguage', lang);
}

// Load saved language on start
document.addEventListener('DOMContentLoaded', () => {
    // Initialize language
    const savedLang = localStorage.getItem('preferredLanguage') || 'en';
    const langSelect = document.getElementById('language-select');
    if (langSelect) {
        langSelect.value = savedLang;
    }
    // Always call changeLanguage even if selector is missing on this specific page
    changeLanguage(savedLang);

    // --- DATA ISOLATION GUARD ---
    // Detect if a different user has logged in and clear stale local data
    const sessionFarmerId = document.body.getAttribute('data-farmer-id');
    if (sessionFarmerId) {
        const storedFarmerId = localStorage.getItem('last_active_farmer_id');

        if (storedFarmerId && storedFarmerId !== sessionFarmerId) {
            console.warn("Storage Guard: Different user detected. Clearing stale local data for safety.");
            const privateKeys = [
                'diseaseHistory', 'alertSettings', 'irrigationDate',
                'waterUsage', 'irrigationCrop', 'irrigationThreshold',
                'irrigationFrequency', 'lastIrrigationTime'
            ];
            privateKeys.forEach(k => localStorage.removeItem(k));
        }

        localStorage.setItem('last_active_farmer_id', sessionFarmerId);
    }
});
